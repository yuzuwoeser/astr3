// Development-only regeneration; normal builds consume the checked-in outline data.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import opentype from 'opentype.js';
import { format, resolveConfig } from 'prettier';

export const revision = 'ffebf8c1ee449e544955a7e813c54f9b73848eac';
const families = ['NotoSans', 'NotoSansSymbols', 'NotoSansSymbols2'];
const fontDirectory = process.argv[2];
const sources = [];
const fonts = [];
for (const family of families) {
  const filename = `${family}-Regular.ttf`;
  const url = `https://raw.githubusercontent.com/notofonts/noto-fonts/${revision}/hinted/ttf/${family}/${filename}`;
  let bytes;
  if (fontDirectory) bytes = readFileSync(join(fontDirectory, filename));
  else {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Could not download ${filename}: ${response.status}`);
    bytes = new Uint8Array(await response.arrayBuffer());
  }
  sources.push({ family, url, sha256: createHash('sha256').update(bytes).digest('hex') });
  fonts.push(
    opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength)),
  );
}
const characters = new Set([
  ...Array.from({ length: 95 }, (_, i) => String.fromCodePoint(32 + i)),
  ...Array.from({ length: 96 }, (_, i) => String.fromCodePoint(160 + i)),
  ...'♈♉♊♋♌♍♎♏♐♑♒♓☉☽☿♀♂♃♄♅♆♇☊☋⚷℞′″–—…',
]);
const round = (value) => Math.round(value * 1000) / 1000;
const glyphs = {};
for (const character of characters) {
  const font = fonts.find((candidate) => candidate.charToGlyphIndex(character) !== 0);
  if (!font)
    throw new Error(
      `Missing export character ${character} U+${character.codePointAt(0).toString(16)}`,
    );
  const glyph = font.charToGlyph(character);
  const path = glyph.getPath(0, 0, 1000);
  const bounds = path.getBoundingBox();
  glyphs[character] = [
    round((glyph.advanceWidth / font.unitsPerEm) * 1000),
    ...[bounds.x1, bounds.y1, bounds.x2, bounds.y2].map(round),
    path.toPathData(3),
  ];
}
const license = readFileSync(new URL('export-fonts/OFL.txt', import.meta.url), 'utf8');
const outlineSource = `// Generated by scripts/generate-export-fonts.mjs; do not edit.\n// SPDX-License-Identifier: OFL-1.1\n// Noto Sans: Copyright 2015-2021 Google LLC. All Rights Reserved.\n// Noto Sans Symbols: Copyright 2016 Google LLC. All Rights Reserved.\n// Noto Sans Symbols 2: Copyright 2017 Google Inc. All Rights Reserved.\n// Full license: export-fonts-OFL.txt in the package; scripts/export-fonts/OFL.txt in source.\n// ${JSON.stringify(sources)}\nexport const EXPORT_GLYPHS: Readonly<Record<string, readonly [number, number, number, number, number, string]>> = ${JSON.stringify(glyphs, null, 2)};\n`;
writeFileSync(
  new URL('../src/export-font-data.ts', import.meta.url),
  await format(outlineSource, {
    ...(await resolveConfig(new URL('../src/export-font-data.ts', import.meta.url).pathname)),
    parser: 'typescript',
  }),
);
writeFileSync(
  new URL('export-fonts/sources.json', import.meta.url),
  JSON.stringify(sources, null, 2) + '\n',
);
// Include notices in published website artifacts as well as the npm distribution.
const siteLicense = new URL('../site/public/THIRD_PARTY_LICENSES.txt', import.meta.url);
const existing = readFileSync(siteLicense, 'utf8').split('\nASTR3 export outlines')[0];
writeFileSync(
  siteLicense,
  existing.trimEnd() + '\n\nASTR3 export outlines — Noto fonts\n\n' + license,
);
console.log(`Generated ${characters.size} outlined characters.`);
